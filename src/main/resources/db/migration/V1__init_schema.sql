-- CareSphere AI — initial schema.
-- Enables the pgvector extension (used by the RAG module in a later milestone)
-- and creates the foundational identity table that authentication builds on.

-- pgvector: required for storing/document embeddings. Safe to call if already present.
CREATE EXTENSION IF NOT EXISTS vector;

-- Identity table for application users (administrators and clinicians).
-- "app_user" avoids the reserved word "user" in PostgreSQL.
CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    full_name     VARCHAR(255) NOT NULL,
    role          VARCHAR(32)  NOT NULL DEFAULT 'CLINICIAN', -- ADMIN | CLINICIAN
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_app_user_email UNIQUE (email)
);

CREATE INDEX idx_app_user_role ON app_user (role);
