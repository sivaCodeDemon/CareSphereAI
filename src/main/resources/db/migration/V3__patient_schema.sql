-- CareSphere AI — patient and medical record tables.
CREATE TABLE patient (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mrn           VARCHAR(32)  NOT NULL,                 -- medical record number (unique)
    first_name    VARCHAR(100) NOT NULL,
    last_name     VARCHAR(100) NOT NULL,
    date_of_birth DATE         NOT NULL,
    gender        VARCHAR(16),
    email         VARCHAR(255),
    phone         VARCHAR(32),
    address       VARCHAR(500),
    created_by     VARCHAR(255),                          -- clinician/admin email who created it
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_patient_mrn UNIQUE (mrn)
);

CREATE INDEX idx_patient_name ON patient (last_name, first_name);

CREATE TABLE medical_record (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id  BIGINT      NOT NULL,
    title       VARCHAR(255) NOT NULL,
    type        VARCHAR(32)  NOT NULL,                    -- NOTE | LAB | PRESCRIPTION | DIAGNOSIS | VITALS | IMAGING
    content     TEXT         NOT NULL,
    recorded_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_medical_record_patient FOREIGN KEY (patient_id) REFERENCES patient (id) ON DELETE CASCADE
);

CREATE INDEX idx_medical_record_patient ON medical_record (patient_id);
