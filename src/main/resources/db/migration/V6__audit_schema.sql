-- CareSphere AI — audit log for security-relevant domain events.
CREATE TABLE audit_event (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor          VARCHAR(255),                          -- authenticated user's email
    action         VARCHAR(50)  NOT NULL,                 -- e.g. CREATE_PATIENT, UPLOAD_DOCUMENT
    resource_type  VARCHAR(32),
    resource_id    BIGINT,
    patient_id     BIGINT,
    status         VARCHAR(16),
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_audit_event_created_at ON audit_event (created_at DESC);
CREATE INDEX idx_audit_event_actor ON audit_event (actor);
