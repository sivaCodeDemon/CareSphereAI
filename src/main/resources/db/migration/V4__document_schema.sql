-- CareSphere AI — uploaded document metadata and extracted text.
-- Embeddings for RAG live in Spring AI's pgvector-managed vector_store table (added in milestone 5).
CREATE TABLE document (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id     BIGINT      NOT NULL,
    filename        VARCHAR(255) NOT NULL,
    content_type    VARCHAR(100) NOT NULL,
    size_bytes      BIGINT      NOT NULL,
    storage_key     VARCHAR(500) NOT NULL,
    page_count     INTEGER,
    extracted_text  TEXT,
    status          VARCHAR(16)  NOT NULL DEFAULT 'PENDING', -- PENDING | EXTRACTED | INDEXED | FAILED
    uploaded_by     VARCHAR(255),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_document_patient FOREIGN KEY (patient_id) REFERENCES patient (id) ON DELETE CASCADE
);

CREATE INDEX idx_document_patient ON document (patient_id);
